# ============================================================
# Logger
# RAG가 질문을 처리한 결과를 운영 로그로 저장합니다.
# 질문, 판정, 재시도 횟수, 오류, 실행 시간 등을 JSONL 파일에 기록합니다.
# ============================================================

import json
import os
import time


# ============================================================
# 질문 처리 결과를 로그 파일에 저장합니다.
# ============================================================

def log_query(question, state, elapsed):

    # --------------------------------------------------------
    # logs 폴더 준비
    # --------------------------------------------------------

    # logs 폴더가 없으면 새로 만듭니다.
    os.makedirs(
        "logs",
        exist_ok=True
    )


    # --------------------------------------------------------
    # 저장할 로그 데이터 만들기
    # --------------------------------------------------------

    record = {

        # 질문을 처리한 시간을 저장합니다.
        "time": time.strftime("%Y-%m-%d %H:%M:%S"),

        # 사용자가 입력한 질문을 저장합니다.
        "question": question,

        # 분류된 질문 종류를 저장합니다.
        "intent": state.get("intent", ""),

        # 검증 결과를 저장합니다.
        "grade": state.get("grade", ""),

        # 답변을 다시 생성한 횟수를 저장합니다.
        "retries": state.get("retries", 0),

        # 검색어를 다시 작성한 횟수를 저장합니다.
        "rewrites": state.get("rewrites", 0),

        # 노드에서 발생한 오류를 저장합니다.
        "node_error": state.get("node_error", ""),

        # 전체 실행 시간을 초 단위로 저장합니다.
        "elapsed": round(elapsed, 2)
    }


    # --------------------------------------------------------
    # 로그 파일에 저장
    # --------------------------------------------------------

    # JSON 데이터를 한 줄씩 파일에 추가합니다.
    with open(
        "logs/queries.jsonl",
        "a",
        encoding="utf-8"
    ) as file:

        # 딕셔너리를 JSON 문자열로 변환합니다.
        text = json.dumps(
            record,
            ensure_ascii=False
        )

        # JSON 한 건을 한 줄에 저장합니다.
        file.write(text + "\n")


    # --------------------------------------------------------
    # 저장한 로그 데이터를 반환
    # --------------------------------------------------------

    return record