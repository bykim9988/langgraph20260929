# ============================================================
# Safe Node
# LangGraph 노드를 안전하게 실행합니다.
# 노드에서 오류가 발생해도 그래프가 중단되지 않도록 합니다.
# ============================================================


def safe_node(fn, state):
    """
    노드 함수를 실행하고,
    오류가 발생하면 오류 정보를 State로 반환합니다.
    """

    try:
        # 원래 노드를 실행합니다.
        result = fn(state)

        # 정상 실행 결과를 그대로 반환합니다.
        return result

    except Exception as e:

        # 발생한 오류를 화면에 출력합니다.
        print("[ERROR]", e)

        # 오류를 State 정보로 바꿔 반환합니다.
        return {
            "node_error": str(e),
            "log": ["노드 실행 중 오류 발생"]
        }