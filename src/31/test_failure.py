# ============================================================
# Safe Node 장애 테스트
# Retriever에서 일부러 오류를 발생시킵니다.
# 오류가 발생해도 전체 그래프가 중단되지 않는지 확인합니다.
# ============================================================

from unittest.mock import patch

import graph31


# ============================================================
# 테스트용 오류 노드
# 실행하면 무조건 오류를 발생시킵니다.
# ============================================================

def broken_node(state):

    # 실제 장애 상황을 가정하여 오류를 발생시킵니다.
    raise RuntimeError(
        "일부러 발생시킨 오류"
    )


# ============================================================
# Retriever 장애 테스트
# ============================================================

# graph31의 retriever_node를 broken_node로 잠시 교체합니다.
with patch(
    "graph31.retriever_node",
    broken_node
):

    # 평소처럼 질문을 실행합니다.
    result = graph31.ask(
        "환불은 며칠 이내인가요?"
    )


    # --------------------------------------------------------
    # 실행 결과 확인
    # --------------------------------------------------------

    # 여기까지 실행되면 그래프가 중단되지 않은 것입니다.
    print("시스템 생존")

    # safe_node가 잡은 오류 내용을 출력합니다.
    print(
        "오류:",
        result["node_error"]
    )