# ============================================================
# test_regression.py
# graph32가 기존 질문에 여전히 올바르게 답하는지 검사합니다.
# 각 답변에 기대한 핵심 키워드가 포함되어 있는지 확인합니다.
# ============================================================

from graph32 import ask


# ============================================================
# 테스트 질문
# ============================================================
# q    : RAG에 입력할 질문
# keys : 정답으로 인정할 핵심 키워드

TESTS = [
    {
        "q": "환불은 며칠 이내인가요?",
        "keys": ["7일"],
    },
    {
        "q": "교환 기간은 얼마인가요?",
        "keys": ["14일"],
    },
    {
        "q": "고객센터 운영 시간은?",
        "keys": ["09:00", "18:00", "9시", "18시"],
    },
    {
        "q": "반품하고 싶은데 언제까지?",
        "keys": ["7일"],
    },
    {
        "q": "물건 바꾸려면 택배비 누가?",
        "keys": ["배송비", "택배비", "고객"],
    },
    {
        "q": "환불 방법과 수수료는?",
        "keys": ["환불", "수수료"],
    },
    {
        "q": "대표이사가 누구인가요?",
        "keys": [
            "관련 자료를 찾지 못했습니다",
            "확인할 수 없습니다",
            "정보가 없습니다",
        ],
    },
]


# ============================================================
# 답변 확인 함수
# ============================================================

def check_answer(answer, keys):
    """답변에 기대한 키워드가 하나라도 있는지 확인합니다."""

    # 키워드를 하나씩 확인
    for key in keys:

        # 답변에 키워드가 있으면 정답
        if key in answer:
            return True

    # 모든 키워드가 없으면 오답
    return False


# ============================================================
# 통계 변수 초기화
# ============================================================

# 정답 개수
correct = 0

# Verifier를 통과한 질문 개수
pass_count = 0

# 답변을 재생성한 질문 개수
retry_count = 0

# 질문을 고쳐 재검색한 질문 개수
rewrite_count = 0


# ============================================================
# 회귀 테스트 실행
# ============================================================

for test in TESTS:

    # 테스트 질문과 정답 키워드 가져오기
    question = test["q"]
    keys = test["keys"]


    # --------------------------------------------------------
    # 1. Modular RAG 실행
    # --------------------------------------------------------

    result = ask(question)


    # --------------------------------------------------------
    # 2. 최종 답변 가져오기
    # --------------------------------------------------------

    answer = result.get("answer", "")


    # --------------------------------------------------------
    # 3. 답변이 맞는지 확인
    # --------------------------------------------------------

    ok = check_answer(
        answer,
        keys
    )

    if ok:

        correct += 1
        mark = "✓"

    else:

        mark = "✗"


    # --------------------------------------------------------
    # 4. Verifier 통과 여부 확인
    # --------------------------------------------------------

    grade = result.get("grade", "")

    if grade == "pass":
        pass_count += 1


    # --------------------------------------------------------
    # 5. 재생성 여부 확인
    # --------------------------------------------------------

    retries = result.get("retries", 0)

    if retries > 0:
        retry_count += 1


    # --------------------------------------------------------
    # 6. 재검색 여부 확인
    # --------------------------------------------------------

    rewrites = result.get("rewrites", 0)

    if rewrites > 0:
        rewrite_count += 1


    # --------------------------------------------------------
    # 7. 질문별 결과 출력
    # --------------------------------------------------------

    print(
        f"{mark} {question} | "
        f"판정={grade} | "
        f"재생성={retries} | "
        f"재검색={rewrites}"
    )


# ============================================================
# 전체 테스트 결과
# ============================================================

# 전체 질문 개수
count = len(TESTS)


print()
print("=" * 50)

# 정답률 계산
accuracy = correct / count * 100

print(
    f"정답률   : "
    f"{correct}/{count} "
    f"({accuracy:.0f}%)"
)

print(
    f"검증통과 : "
    f"{pass_count}/{count}"
)

print(
    f"재생성   : "
    f"{retry_count}건"
)

print(
    f"재검색   : "
    f"{rewrite_count}건"
)

print("=" * 50)