# ============================================================
# test_coverage.py
# graph32의 여러 실행 경로를 테스트합니다.
# 모든 노드가 최소 한 번 이상 실행되는지 확인합니다.
# ============================================================

from graph32 import app
from graph_state2 import make_initial_state


# ============================================================
# 테스트 질문
# ============================================================
# 각 질문은 서로 다른 경로를 실행하기 위해 준비합니다.

CASES = [
    ("안녕하세요", "greeting 경로"),
    ("120 * 3 + 45", "calc 경로"),
    ("오늘 날씨 어때요?", "scope 경로"),
    ("환불은 며칠 이내인가요?", "정상 RAG 경로"),
    ("반품하고 싶은데 언제까지?", "재검색 경로"),
    ("환불 방법과 수수료는?", "재생성 경로"),
    ("대표이사가 누구인가요?", "fallback 경로"),
]


# ============================================================
# 전체 노드 목록
# ============================================================

ALL_NODES = [
    "classify",
    "greeting",
    "calc",
    "scope",
    "retrieve",
    "generate",
    "verify",
    "bump",
    "rewrite",
    "fallback",
]


# ============================================================
# 노드별 방문 횟수 초기화
# ============================================================

visited = {}

for node_name in ALL_NODES:
    visited[node_name] = 0


# ============================================================
# 테스트 실행
# ============================================================

for question, description in CASES:

    # 질문으로 초기 State 생성
    state = make_initial_state(question)

    # 이번 질문에서 방문한 노드를 저장
    nodes = []


    # --------------------------------------------------------
    # 그래프를 한 단계씩 실행
    # --------------------------------------------------------

    for step in app.stream(
        state,
        {"recursion_limit": 40}
    ):

        # 현재 단계에서 실행된 노드 확인
        for node_name in step.keys():

            # 실행된 노드 이름 저장
            nodes.append(node_name)

            # 해당 노드의 방문 횟수 증가
            visited[node_name] += 1


    # --------------------------------------------------------
    # 질문별 실행 경로 출력
    # --------------------------------------------------------

    print()
    print(f"[{description}]")
    print(f"질문: {question}")
    print(f"경로: {' -> '.join(nodes)}")


# ============================================================
# 노드별 방문 횟수 출력
# ============================================================

print()
print("=" * 50)
print("노드별 방문 횟수")
print("=" * 50)


for node_name in ALL_NODES:

    # 해당 노드의 방문 횟수
    count = visited[node_name]

    # 한 번 이상 실행되었는지 확인
    if count > 0:
        mark = "✓"

    else:
        mark = "✗ 미방문"

    print(
        f"{node_name:<10} "
        f"{count:>3}회  "
        f"{mark}"
    )


# ============================================================
# 미방문 노드 확인
# ============================================================

missing = []

for node_name in ALL_NODES:

    # 한 번도 실행되지 않은 노드 저장
    if visited[node_name] == 0:
        missing.append(node_name)


# ============================================================
# 최종 결과 출력
# ============================================================

print("=" * 50)


if len(missing) == 0:

    print(
        "✓ 모든 노드를 최소 1회 이상 방문했습니다."
    )

else:

    print(
        "✗ 미방문 노드:",
        ", ".join(missing)
    )