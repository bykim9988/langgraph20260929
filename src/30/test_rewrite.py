import os
import sys


# ------------------------------------------------------------
# 필요한 모듈의 경로를 설정합니다.
# ------------------------------------------------------------

# 현재 파일이 있는 30차시 폴더입니다.
CURRENT_DIR = os.path.dirname(os.path.abspath(__file__))

# 공통 파일이 있는 src 폴더입니다.
SRC_DIR = os.path.abspath(os.path.join(CURRENT_DIR, ".."))

# src 폴더를 Python 검색 경로에 추가합니다.
sys.path.insert(0, SRC_DIR)

# 이전 차시에서 만든 모듈을 사용할 수 있게 합니다.
for folder in ["18", "19", "24", "25", "26", "29"]:

    path = os.path.join(SRC_DIR, folder)

    sys.path.append(path)

# 현재 30차시 모듈을 가장 먼저 찾도록 합니다.
sys.path.insert(0, CURRENT_DIR)


# ------------------------------------------------------------
# 30차시 그래프와 초기 State 생성 함수를 가져옵니다.
# ------------------------------------------------------------

from graph30 import app
from graph_state2 import make_initial_state


# ============================================================
# 테스트 질문
# 일상적인 표현 때문에 검색에 실패하기 쉬운 질문입니다.
# ============================================================

QUESTIONS = [
    "반품하고 싶은데 언제까지 가능해요?",
    "물건 바꾸려면 택배비 누가 내나요?",
    "돈 돌려받으려면 어떻게 해요?",
]


# ============================================================
# 테스트 실행
# 각 질문을 그래프에 전달하고 Rewrite 결과를 확인합니다.
# ============================================================

for question in QUESTIONS:

    # 질문 구분선을 출력합니다.
    print("\n" + "=" * 60)
    print("Q:", question)
    print("=" * 60)


    # --------------------------------------------------------
    # 1. 질문으로 초기 State를 만듭니다.
    # --------------------------------------------------------

    state = make_initial_state(question)


    # --------------------------------------------------------
    # 2. LangGraph를 실행합니다.
    # --------------------------------------------------------

    result = app.invoke(
        state,
        {
            "recursion_limit": 30
        }
    )


    # --------------------------------------------------------
    # 3. 최종 답변을 출력합니다.
    # --------------------------------------------------------

    print(
        "A:",
        result.get("answer", "")
    )


    # --------------------------------------------------------
    # 4. Rewrite 횟수를 출력합니다.
    # --------------------------------------------------------

    print(
        "재작성:",
        result.get("rewrites", 0),
        "회"
    )


    # --------------------------------------------------------
    # 5. 마지막으로 사용한 검색어를 출력합니다.
    # --------------------------------------------------------

    print(
        "최종 검색어:",
        result.get("query", "")
    )


    # --------------------------------------------------------
    # 6. 지금까지 사용한 검색어를 모두 출력합니다.
    # --------------------------------------------------------

    print(
        "시도한 검색어:",
        result.get("tried_queries", [])
    )


    # --------------------------------------------------------
    # 7. 최종 검증 결과를 출력합니다.
    # --------------------------------------------------------

    print(
        "최종 판정:",
        result.get("grade", "")
    )