# ============================================================
# LangGraph RAG 시스템에서 사용할 전체 State를 정의합니다.
# 각 노드가 사용할 데이터와 초기값을 한곳에서 관리합니다.
# log와 tried_queries는 Reducer를 사용하여 값을 계속 누적합니다.
# ============================================================

from typing import TypedDict, Annotated, List
import operator


# ============================================================
# 1. RAG State 정의
# ============================================================

class RAGState(TypedDict):
    """LangGraph의 모든 노드가 공유하는 State입니다."""

    # --------------------------------------------------------
    # 기본 질문
    # --------------------------------------------------------

    # 사용자가 처음 입력한 질문
    question: str

    # 실제 검색에 사용하는 질문
    query: str


    # --------------------------------------------------------
    # 29차시 - 질문 분류
    # --------------------------------------------------------

    # 질문 종류
    intent: str


    # --------------------------------------------------------
    # Retriever
    # --------------------------------------------------------

    # 검색된 문서
    documents: list

    # 검색된 문서의 유사도 점수
    scores: list

    # 검색 성공 여부
    retrieval_ok: bool

    # 검색 실패 이유
    fail_reason: str


    # --------------------------------------------------------
    # Generator
    # --------------------------------------------------------

    # 생성된 답변
    answer: str

    # 근거 부족 여부
    insufficient: bool

    # 답변에 출처가 포함되었는지 여부
    has_citation: bool

    # 답변 생성 중 발생한 오류
    gen_error: str


    # --------------------------------------------------------
    # Verifier
    # --------------------------------------------------------

    # 검증 결과
    grade: str

    # 검증 결과의 이유
    reason: str


    # --------------------------------------------------------
    # 재생성
    # --------------------------------------------------------

    # 답변 재생성 횟수
    retries: int


    # --------------------------------------------------------
    # 30차시 - Rewrite
    # --------------------------------------------------------

    # 검색어 재작성 횟수
    rewrites: int

    # 지금까지 사용한 검색어를 계속 누적
    tried_queries: Annotated[List[str], operator.add]


    # --------------------------------------------------------
    # 전체 실행 로그
    # --------------------------------------------------------

    # 각 노드의 실행 기록을 계속 누적
    log: Annotated[List[str], operator.add]


# ============================================================
# 2. 초기 State 생성
# ============================================================

def make_initial_state(question: str) -> dict:
    """사용자 질문을 받아 처음 사용할 State를 만듭니다."""

    return {
        # 기본 질문
        "question": question,
        "query": question,

        # 질문 분류
        "intent": "",

        # Retriever
        "documents": [],
        "scores": [],
        "retrieval_ok": False,
        "fail_reason": "",

        # Generator
        "answer": "",
        "insufficient": False,
        "has_citation": False,
        "gen_error": "",

        # Verifier
        "grade": "",
        "reason": "",

        # 재생성 횟수
        "retries": 0,

        # 검색어 재작성 횟수
        "rewrites": 0,

        # 최초 검색어 기록
        "tried_queries": [question],

        # 실행 로그
        "log": [],
    }