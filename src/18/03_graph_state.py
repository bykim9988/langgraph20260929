# ============================================================
# RAG 그래프 전체에서 공유할 State 구조를 정의합니다.
# 질문, 검색 결과, 답변, 검증 결과, 재시도 정보 등을 하나의 State로 관리합니다.
# log와 tried_queries는 Reducer를 사용해 기존 값에 계속 누적합니다.
# ============================================================

from typing import TypedDict, Annotated, Any
import operator


# ============================================================
# RAG State 정의
# ============================================================

class RAGState(TypedDict, total=False):
    """RAG 그래프의 모든 노드가 함께 사용하는 데이터 구조입니다."""

    # --------------------------------------------------------
    # 1. 사용자 입력
    # --------------------------------------------------------

    # 사용자가 처음 입력한 질문입니다.
    question: str

    # 실제 검색에 사용할 질문입니다.
    # 검색 실패 시 다른 문장으로 변경할 수 있습니다.
    query: str


    # --------------------------------------------------------
    # 2. 검색 결과
    # --------------------------------------------------------

    # 검색된 문서 조각들을 저장합니다.
    documents: list[Any]

    # 검색된 문서들의 유사도 점수를 저장합니다.
    scores: list[float]

    # 검색 결과를 사용할 수 있는지 저장합니다.
    retrieval_ok: bool


    # --------------------------------------------------------
    # 3. 답변 생성 결과
    # --------------------------------------------------------

    # LLM이 생성한 최종 답변입니다.
    answer: str

    # 근거가 부족한지 저장합니다.
    insufficient: bool

    # 답변에 출처 번호가 포함되었는지 저장합니다.
    has_citation: bool


    # --------------------------------------------------------
    # 4. 답변 검증 결과
    # --------------------------------------------------------

    # 답변 검증 결과를 저장합니다.
    # 예: "pass", "retry"
    grade: str

    # 검증 결과가 나온 이유를 저장합니다.
    reason: str


    # --------------------------------------------------------
    # 5. 그래프 제어 정보
    # --------------------------------------------------------

    # 답변 생성 등을 다시 시도한 횟수입니다.
    retries: int

    # 검색할 문서 개수입니다.
    top_k: int


    # --------------------------------------------------------
    # 6. 실행 이력
    # --------------------------------------------------------

    # 각 노드의 실행 기록을 계속 누적합니다.
    log: Annotated[list[str], operator.add]

    # 지금까지 사용한 검색어를 계속 누적합니다.
    tried_queries: Annotated[list[str], operator.add]